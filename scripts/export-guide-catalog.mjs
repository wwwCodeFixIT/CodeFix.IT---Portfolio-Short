import { mkdir, readFile, writeFile } from 'node:fs/promises'
import ts from 'typescript'

// Keep the editorial TypeScript file as the source of truth, outside the browser bundle.
const source = await readFile(new URL('../src/data/wordpress-guides.ts', import.meta.url), 'utf8')
const { outputText } = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.ESNext },
})
const { wordpressGuides } = await import(
  `data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`
)
await mkdir(new URL('../public/data/', import.meta.url), { recursive: true })
await writeFile(
  new URL('../public/data/wordpress-guides.json', import.meta.url),
  JSON.stringify(wordpressGuides),
)
const summaries = wordpressGuides.map(
  ({ slug, title, serviceHref, description, intent, contactHint }) => ({
    slug,
    title,
    serviceHref,
    description,
    intent,
    contactHint,
  }),
)
await writeFile(
  new URL('../src/data/guide-summaries.ts', import.meta.url),
  '// Generated by scripts/export-guide-catalog.mjs from wordpress-guides.ts.\n' +
    'export const guideSummaries = ' +
    JSON.stringify(summaries, null, 2) +
    ';\n',
)
console.log(`Exported ${wordpressGuides.length} guides and lightweight summaries.`)
